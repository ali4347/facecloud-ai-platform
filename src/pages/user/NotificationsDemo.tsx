import { useState } from 'react'
import { PageHeader } from '../../components/layout/PageHeader'
import { ChartCard } from '../../components/ui/ChartCard'
import { Bell, CheckCheck, Trash2, Mail, CheckCircle2, AlertTriangle, FileCheck } from 'lucide-react'

export default function NotificationsDemo() {
  const [list, setList] = useState([
    { id: 1, type: 'success', title: 'Zero-DCE Restores completed', msg: 'Face portrait exposure coefficient restored and enhanced image saved.', time: '10 mins ago', read: false, icon: FileCheck },
    { id: 2, type: 'success', title: 'Person Folder created', msg: 'FaceNet clustering mapped 3 identical face assets into Person Cluster 1.', time: '1 hour ago', read: false, icon: CheckCircle2 },
    { id: 3, type: 'error', title: 'Face Validation Failed', msg: 'Asset blurry_shaky_003.jpg rejected. High motion blur index calculated.', time: '2 hours ago', read: true, icon: AlertTriangle },
    { id: 4, type: 'info', title: 'Email Notification sent', msg: 'Mock notification report dispatched successfully to user@facecloud.ai.', time: '3 hours ago', read: true, icon: Mail },
    { id: 5, type: 'success', title: 'Batch ZIP file generated', msg: 'Batch zip archive upload-1002 unpacked and processed with 95% throughput.', time: '1 day ago', read: true, icon: FileCheck },
    { id: 6, type: 'info', title: 'Secure download link generated', msg: 'Secure token link mapped with 7-day expiration thresholds.', time: '2 days ago', read: true, icon: Mail }
  ])

  const markAllRead = () => {
    setList(prev => prev.map(n => ({ ...n, read: true })))
  }

  const clearAll = () => {
    setList([])
  }

  return (
    <div className="space-y-6">
      <PageHeader 
        title="In-App Notifications"
        subtitle="Manage alerts generated by background biometrics workflows and email queues."
      />

      <div className="max-w-4xl mx-auto space-y-4">
        
        {/* Controls */}
        <div className="flex justify-between items-center text-xs font-bold text-ink-mute">
          <span>{list.filter(n => !n.read).length} unread alerts</span>
          <div className="flex gap-4">
            <button onClick={markAllRead} className="hover:text-accent flex items-center gap-1">
              <CheckCheck className="w-3.5 h-3.5 text-emerald-400" /> Mark all read
            </button>
            <button onClick={clearAll} className="hover:text-accent-soft flex items-center gap-1">
              <Trash2 className="w-3.5 h-3.5 text-accent-soft" /> Clear alerts
            </button>
          </div>
        </div>

        {/* Alerts List */}
        <ChartCard title="System Alerts Feed" subtitle="Real-time alert queues">
          {list.length === 0 ? (
            <div className="h-64 flex flex-col items-center justify-center text-center text-ink-mute gap-2">
              <Bell className="w-8 h-8 text-ink-mute opacity-40 animate-bounce" />
              <p className="text-xs font-semibold">You have no notification logs at present.</p>
            </div>
          ) : (
            <div className="space-y-3">
              {list.map(n => (
                <div 
                  key={n.id} 
                  className={`p-4 rounded-3xl border transition-all flex items-start gap-4 ${
                    !n.read ? 'bg-accent/5 border-accent/20 ring-1 ring-accent/10' : 'bg-surface-mute border-line opacity-80'
                  }`}
                >
                  <div className={`p-2.5 rounded-2xl bg-surface-mute border border-line ${
                    n.type === 'success' ? 'text-emerald-400' :
                    n.type === 'error' ? 'text-accent-soft' : 'text-accent'
                  }`}>
                    <n.icon className="w-4 h-4" />
                  </div>
                  
                  <div className="flex-1 text-xs">
                    <div className="flex justify-between items-center">
                      <h4 className="font-bold text-ink">{n.title}</h4>
                      <span className="text-[10px] text-ink-mute">{n.time}</span>
                    </div>
                    <p className="text-[#8A96AD] mt-1 leading-relaxed">{n.msg}</p>
                  </div>
                </div>
              ))}
            </div>
          )}
        </ChartCard>

      </div>
    </div>
  )
}
