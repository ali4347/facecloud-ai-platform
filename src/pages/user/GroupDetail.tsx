import { useParams, Link } from 'react-router-dom'
import { PageHeader } from '../../components/layout/PageHeader'
import { ChartCard } from '../../components/ui/ChartCard'
import { mockGroups, mockImages } from '../../data/mock'
import { ArrowLeft, CheckCircle, Download, Link2, Eye } from 'lucide-react'

export default function GroupDetail() {
  const { id } = useParams<{ id: string }>()
  
  // Find group
  const group = mockGroups.find(g => g.id === id) || mockGroups[0]
  
  // Filter images matching this folder
  const images = mockImages.filter(img => img.personFolderId === group.id)

  return (
    <div className="space-y-6">
      <div className="flex items-center gap-3">
        <Link to="/dashboard/groups" className="p-2 rounded-xl hover:bg-white/5 border border-white/10 text-muted hover:text-white">
          <ArrowLeft className="w-4 h-4" />
        </Link>
        <PageHeader 
          title={`Person Folder: ${group.label}`}
          subtitle="Inspect cluster folders generated by biometrics embedding models."
        />
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
        
        {/* Left Column: Folders items list */}
        <div className="lg:col-span-8 space-y-6">
          <ChartCard title="Folder Contents" subtitle={`${images.length} images mapped in this identity group`}>
            <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
              {images.map(img => (
                <div key={img.id} className="p-4 rounded-3xl bg-white/5 border border-white/10 flex flex-col justify-between aspect-square hover:border-primary/40 transition-all">
                  <div className="aspect-[4/3] rounded-2xl overflow-hidden bg-black/10 border border-white/5 relative">
                    {/* Simulated face frame using color swatch */}
                    <div className="absolute inset-0" style={{ backgroundColor: img.thumbnail }} />
                    <span className="absolute top-2 right-2 px-1.5 py-0.5 rounded bg-black/40 text-[8px] text-white font-mono uppercase font-bold tracking-wider">
                      {img.dimensions}
                    </span>
                  </div>

                  <div className="mt-3 flex items-center justify-between text-xs">
                    <div className="min-w-0 flex-1 pr-2">
                      <p className="font-bold text-dark truncate">{img.filename}</p>
                      <p className="text-[10px] text-muted mt-0.5">{img.size}</p>
                    </div>
                    <Link 
                      to={`/dashboard/images/${img.id}`}
                      className="p-1.5 rounded-lg bg-primary/10 border border-primary/20 text-primary hover:bg-primary/20"
                    >
                      <Eye className="w-3.5 h-3.5" />
                    </Link>
                  </div>
                </div>
              ))}
            </div>
          </ChartCard>
        </div>

        {/* Right Column: Actions / Stats */}
        <div className="lg:col-span-4">
          <ChartCard title="Biometrics Folder Stats" subtitle="Clustering analytics">
            <div className="space-y-6">
              
              <div className="p-4 rounded-3xl bg-white/5 border border-white/10 text-xs text-muted space-y-3.5">
                <div className="flex justify-between items-center text-[10px] font-bold uppercase tracking-wider pb-1.5 border-b border-white/5">
                  <span>Cluster Details</span>
                  <span className="text-mint font-bold flex items-center gap-1"><CheckCircle className="w-3 h-3" /> MATCHED</span>
                </div>
                <div className="flex justify-between">
                  <span>Folder Index ID:</span>
                  <span className="font-bold text-dark">{group.id}</span>
                </div>
                <div className="flex justify-between">
                  <span>Matching Confidence:</span>
                  <span className="font-bold text-mint">{group.matchingConfidence}% Average</span>
                </div>
                <div className="flex justify-between">
                  <span>Folder Created:</span>
                  <span className="font-bold text-dark">{new Date(group.createdDate).toLocaleDateString()}</span>
                </div>
                <div className="flex justify-between">
                  <span>Total Linked assets:</span>
                  <span className="font-bold text-dark">{images.length} files</span>
                </div>
              </div>

              <div className="space-y-3">
                <button 
                  onClick={() => alert(`Downloading ZIP for folder ${group.label}...`)}
                  className="fc-btn-primary w-full justify-center text-xs py-3"
                >
                  <Download className="w-4 h-4" /> Download Folder ZIP
                </button>
                <button 
                  onClick={() => {
                    navigator.clipboard.writeText(`https://facecloud.ai/download/group-sec-${group.id}`)
                    alert('Secure folder link copied to clipboard!')
                  }}
                  className="fc-btn-secondary w-full justify-center text-xs py-3"
                >
                  <Link2 className="w-4 h-4" /> Copy Secure Link
                </button>
              </div>

            </div>
          </ChartCard>
        </div>

      </div>
    </div>
  )
}
